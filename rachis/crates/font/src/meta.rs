//! What the fonts say about themselves: version, copyright, licence, vendor, and the fixed creation time that
//! makes a build reproducible.

/// The font revision, `head.fontRevision` and name ID 5: major.thousandths.
pub const VERSION: (u16, u16) = (1, 0);

/// Name ID 0.
pub const COPYRIGHT: &str =
    "Copyright 2026 The Rachis Project Authors (https://github.com/ethan-wickstrom/experiments)";

/// Name ID 10.
pub const DESCRIPTION: &str = "A monospaced typeface for code, plain-text mathematics and terminal interfaces, \
     generated by a program.";

/// Name ID 11: where the type's makers are.
pub const VENDOR_URL: &str = "https://github.com/ethan-wickstrom/experiments";

/// Name ID 13.
pub const LICENSE: &str = "This Font Software is licensed under the SIL Open Font License, Version 1.1. \
     This license is available with a FAQ at: https://openfontlicense.org";

/// Name ID 14.
pub const LICENSE_URL: &str = "https://openfontlicense.org";

/// `OS/2.achVendID` and the middle of name ID 3: four characters; this value marks an unregistered vendor.
pub const VENDOR: &[u8; 4] = b"NONE";

/// The fonts' creation time in seconds since 1970-01-01 UTC (2026-11-15 00:00:00). It is fixed per release so
/// that the same source gives the same bytes; `head.created` and `head.modified` both carry it.
pub const EPOCH: i64 = 1_794_700_800;

/// Seconds from 1904-01-01 (the `head` table's epoch) to 1970-01-01.
pub const MAC_EPOCH_OFFSET: i64 = 2_082_844_800;

/// The version as name ID 5 and the start of name ID 3 write it: "1.000".
pub fn version_string() -> String {
    format!("{}.{:03}", VERSION.0, VERSION.1)
}
